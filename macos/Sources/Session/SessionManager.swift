    func sendEditorSave(docId: UInt64) {
        guard state == .running else { return }
        broadcast(.editorSave(docId: docId))
    }

    func sendEditorSaved(docId: UInt64, rev: UInt32) {
        guard role == .host, state == .running else { return }
