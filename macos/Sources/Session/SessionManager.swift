    func sendHeartbeat() {
        guard state == .running else { return }
        broadcast(.heartbeat)
    }

    // MARK: polling

    private func startPolling() {
        pollTimer?.cancel()
        let t = DispatchSource.makeTimerSource(queue: .main)
        pollTimer = t
        pollIntervalMs = 16
        t.setEventHandler { [weak self] in
            MainActor.assumeIsolated {
                guard let self = self else { return }
                let drained = self.pump()
                self.schedulePump(drained: drained)
            }
        }
        t.schedule(deadline: .now() + .milliseconds(pollIntervalMs))
        t.resume()
    }

    /// Pick the next pump interval based on activity. Backoff schedule:
    /// 16 ms (active) → 33 ms → 66 ms (steady idle, peer connected),
    /// or 200 ms when no remote peer is connected. Any drain > 0 snaps
    /// back to 16 ms so interactive latency stays unaffected. Cheap: just
    /// re-arms the existing DispatchSourceTimer.
    private func schedulePump(drained: Int) {
        guard let t = pollTimer else { return }
        let next: Int
        if drained > 0 {
            next = 16
        } else if participants.count <= 1 {
            // No remote peers — `ct_session_poll` can't produce frames.
            next = 200
        } else {
            switch pollIntervalMs {
            case ..<33: next = 33
            case 33..<66: next = 66
            default: next = 66
            }
        }
        pollIntervalMs = next
        t.schedule(deadline: .now() + .milliseconds(next))
    }

    private func startKeepAlive() {
        keepAliveTimer?.invalidate()
        keepAliveTimer = Timer.scheduledTimer(
            withTimeInterval: Self.keepAliveInterval,
            repeats: true
        ) { [weak self] _ in
            MainActor.assumeIsolated { self?.sendHeartbeat() }
        }
    }

    private var borePumpTickCount: Int = 0
    private func startBorePumping() {
        NSLog("[ct] startBorePumping scheduling timer")
        borePumpTickCount = 0
        borePumpTimer = Timer.scheduledTimer(withTimeInterval: 0.2, repeats: true) { [weak self] t in
            MainActor.assumeIsolated {
                guard let self = self, let b = self.boreHandle else {
                    NSLog("[ct] bore pump timer: no handle, invalidating")
                    t.invalidate()
                    return
                }
                self.borePumpTickCount += 1
                var buf = [UInt8](repeating: 0, count: 256)
                let n = buf.withUnsafeMutableBufferPointer { p -> Int in
                    Int(ct_bore_pump(b, p.baseAddress, p.count))
                }
                if self.borePumpTickCount <= 5 || self.borePumpTickCount % 5 == 0 {
                    NSLog("[ct] bore pump tick=%d rc=%d", self.borePumpTickCount, n)
                }
                if n > 0 {
                    var url = String(bytes: buf.prefix(min(n, buf.count)), encoding: .utf8)
                    if let keyFrag = self.sessionKey?.base64url {
                        url = url.map { "cotty://join?addr=\($0)&k=\(keyFrag)" }
                    } else {
                        url = url.map { "cotty://join?addr=\($0)" }
                    }
                    self.publicURL = url
                    NSLog("[ct] bore url ready: %@", url ?? "<nil>")
                    t.invalidate()
                } else if n < 0 {
                    // Snapshot whatever bore has printed so we can diagnose.
                    var dbuf = [UInt8](repeating: 0, count: 4096)
                    let dlen = dbuf.withUnsafeMutableBufferPointer { p -> Int in
                        Int(ct_bore_debug(b, p.baseAddress, p.count))
                    }
                    let preview = String(bytes: dbuf.prefix(min(dlen, dbuf.count)),
                                         encoding: .utf8) ?? "<binary>"
                    let trimmed = preview.trimmingCharacters(in: .whitespacesAndNewlines)
                    self.lastError = trimmed.isEmpty
                        ? "bore exited before reporting a public URL"
                        : trimmed
                    NSLog("[ct] bore pump rc=-1 bufferedLen=%d preview=%@",
                          dlen, preview)
                    t.invalidate()
                    // Free the handle so startBoreTunnel can be called again (retry).
                    ct_bore_free(b)
                    self.boreHandle = nil
                }
            }
        }
    }

    @discardableResult
    private func pump() -> Int {
        return drainFrames() + drainEvents()
    }

    @discardableResult
    private func drainEvents() -> Int {
        var count = 0
        for _ in 0..<32 {
            // Re-check every iteration: an event handler may have called
            // stop() (e.g. peer-side on host disconnect), freeing the handle.
            guard let h = handle else { return count }
            var kind: UInt8 = 0
            var peerID: UInt32 = 0
            let r = ct_session_poll_event(h, &kind, &peerID)
            if r == 0 { return count }
            count += 1
            switch kind {
            case 0: handleConnected(peerID)
            case 1: handleDisconnected(peerID)
            default: break
            }
        }
        return count
    }

    @discardableResult
    private func drainFrames() -> Int {
        var buf = [UInt8](repeating: 0, count: 64 * 1024)
        var count = 0
        for _ in 0..<64 {
            guard let h = handle else { return count }
            var peerID: UInt32 = 0
            let n = buf.withUnsafeMutableBufferPointer { p -> Int in
                Int(ct_session_poll(h, p.baseAddress, p.count, &peerID))
            }
            if n == 0 { return count }
            if n > buf.count {
                buf = [UInt8](repeating: 0, count: n)
                continue
            }
            count += 1
            let wire = Data(buf.prefix(n))
            do {
                let plain: Data
                if let key = sessionKey {
                    plain = try key.decrypt(wire)
                } else {
                    plain = wire
                }
                let frame = try FrameCodec.decode(plain)
                handleFrame(frame, from: peerID)
            } catch {
                lastError = "decode: \(error)"
            }
        }
        return count
    }

    // MARK: event / frame handlers

    private func handleConnected(_ peerID: UInt32) {
        // Host: a peer's TCP just landed; roster updates on their Hello.
        // On the peer side the one "connected" event is the host socket —
        // no state change needed until the host's Roster arrives.
        _ = peerID
    }

    private func handleDisconnected(_ peerID: UInt32) {
        if role == .host {
            if let gone = transportToIdentity.removeValue(forKey: peerID) {
                // A reconnecting peer may already be back on a new transport
                // connection before the old socket's death is noticed — only
                // drop them from the roster when this was their last one.
                if !transportToIdentity.values.contains(gone) {
                    participants.removeAll { $0.identity == gone }
                }
                broadcastRoster()
            }
        } else {
            // Peer-side: the host connection dropped. Auto-retry the join
            // with backoff (#61); tear down only if we never had a target.
            if lastJoinHost != nil {
                beginReconnect()
            } else {
                stop()
                state = .disconnected
            }
        }
    }

    // MARK: reconnect (peer only)

    /// Backoff before reconnect `attempt` (1-based): 1s, 2s, 4s, …, 30s cap.
    private static func reconnectDelay(attempt: Int) -> TimeInterval {
        min(30, pow(2, Double(attempt - 1)))
    }

    /// Tear down the dead transport but keep identity, session key, role,
    /// and roster so the session can resume in place.
    private func beginReconnect() {
        pollTimer?.cancel(); pollTimer = nil
        keepAliveTimer?.invalidate(); keepAliveTimer = nil
        if let h = handle {
            ct_session_free(h)
            handle = nil
        }
        reconnectAttempt = 0
        onReconnectBegan?()
        scheduleReconnect()
    }

    private func scheduleReconnect() {
        reconnectAttempt += 1
        guard reconnectAttempt <= Self.maxReconnectAttempts else {
            NSLog("[ct] reconnect gave up after %d attempts", Self.maxReconnectAttempts)
            stop()
            state = .disconnected
            return
        }
        state = .reconnecting(attempt: reconnectAttempt)
        let delay = Self.reconnectDelay(attempt: reconnectAttempt)
        NSLog("[ct] reconnect attempt %d/%d in %.0fs",
              reconnectAttempt, Self.maxReconnectAttempts, delay)
        reconnectTimer?.invalidate()
        reconnectTimer = Timer.scheduledTimer(
            withTimeInterval: delay,
            repeats: false
        ) { [weak self] _ in
            MainActor.assumeIsolated { self?.attemptReconnect() }
        }
    }

    private func attemptReconnect() {
        guard case .reconnecting = state, let host = lastJoinHost else { return }
        let port = lastJoinPort
        let generation = reconnectGeneration
        // Connect off the main actor — a vanished host can leave the TCP
        // handshake hanging far longer than any acceptable UI stall. The
        // handle crosses back as a bit pattern because OpaquePointer is
        // not Sendable.
        Task.detached(priority: .userInitiated) { [weak self] in
            let bits = host.withCString { cstr in
                Int(bitPattern: ct_session_new_peer(cstr, port))
            }
            guard let self else {
                // Manager died while connecting; don't leak the socket.
                if let h = OpaquePointer(bitPattern: bits) { ct_session_free(h) }
                return
            }
            await self.finishReconnectAttempt(handleBits: bits, generation: generation)
        }
    }

    private func finishReconnectAttempt(handleBits: Int, generation: Int) {
        let newHandle = OpaquePointer(bitPattern: handleBits)
        // The user stopped or left the session while the connect was in
        // flight — discard the orphaned connection.
        guard generation == reconnectGeneration, case .reconnecting = state else {
            if let h = newHandle { ct_session_free(h) }
            return
        }
        guard let h = newHandle else {
            NSLog("[ct] reconnect attempt %d failed: %@",
                  reconnectAttempt, Self.readLastError() ?? "unknown error")
            scheduleReconnect()
            return
        }
        NSLog("[ct] reconnected after %d attempt(s)", reconnectAttempt)
        handle = h
        reconnectAttempt = 0
        state = .running
        startPolling()
        startKeepAlive()
        // Let the UI reset join-time state before Hello triggers the host's
        // re-join snapshot.
        onReconnected?()
        sendHello()
    }

    private func handleFrame(_ frame: Frame, from peerID: UInt32) {
        switch frame {
        case .hello(let id, let helloRole, let color, let name):
            if role == .host {
                transportToIdentity[peerID] = id
                upsertParticipant(identity: id, role: helloRole,
                                  name: name, color: color)
                broadcastRoster()
            }
        case .roster(let entries):
            if role == .peer {
                // Peer: replace participants with authoritative list.
                var next: [Participant] = entries.map {
                    Participant(identity: $0.identity,
                                role: $0.role,
                                name: $0.name,
                                color: $0.color)
                }
                // Make sure our own entry is present with our current name.
                if !next.contains(where: { $0.identity == localIdentity }) {
                    next.append(Participant(
                        identity: localIdentity, role: .peer,
                        name: localName, color: localColor))
                }
                if let localEntry = next.first(where: { $0.identity == localIdentity }) {
                    localColor = localEntry.color
                }
                participants = next
            }
        case .modeChange(let m):
            if role == .peer { remoteMode = m }
        case .accessMode(let m):
            if role == .peer { accessMode = m }
        case .heartbeat:
            break
        case .kick(let id):
            _ = id  // ContentView.handleInbound handles teardown and notification
        default:
            break
        }
        onFrame?(frame, peerID)
    }

    // MARK: participants / roster

    private func upsertParticipant(identity: UserIdentity,
                                   role helloRole: SessionRole,
                                   name: String,
                                   color: UInt32)
    {
        let resolvedColor = resolvedParticipantColor(
            for: identity,
            preferredColor: color)
        if let i = participants.firstIndex(where: { $0.identity == identity }) {
            participants[i].role = helloRole
            participants[i].name = name
            participants[i].color = resolvedColor
        } else {
            participants.append(Participant(
                identity: identity, role: helloRole,
                name: name, color: resolvedColor))
        }
    }

    /// Override a participant's rendered cursor color. Used by the UI layer to
    /// apply theme-derived (per-viewer) colors; no-op if unchanged.
    func setParticipantColor(_ identity: UserIdentity, to color: UInt32) {
        if let i = participants.firstIndex(where: { $0.identity == identity }),
           participants[i].color != color {
            participants[i].color = color
        }
    }

    private func resolvedParticipantColor(for identity: UserIdentity,
                                          preferredColor: UInt32) -> UInt32
    {
        let usedColors = Set(
            participants
                .filter { $0.identity != identity }
                .map(\.color))
        if !usedColors.contains(preferredColor) {
            return preferredColor
        }

        let palette = Self.participantPalette
        guard !palette.isEmpty else { return preferredColor }

        let start = Int(Self.colorHash(for: identity) % UInt32(palette.count))
        for offset in 0..<palette.count {
            let candidate = palette[(start + offset) % palette.count]
            if !usedColors.contains(candidate) {
                return candidate
            }
        }
        return preferredColor
    }

    private func updateLocalParticipantField(_ mutate: (inout Participant) -> Void) {
        if let i = participants.firstIndex(where: { $0.identity == localIdentity }) {
            mutate(&participants[i])
        }
    }

    /// Host only: broadcast the current full roster to all peers.
    private func broadcastRoster() {
        guard role == .host else { return }
        let entries = participants.map {
            RosterEntry(identity: $0.identity, role: $0.role,
                        color: $0.color, name: $0.name)
        }
        broadcast(.roster(entries))
    }

    // MARK: persisted name

    static let nameDefaultsKey = "CoTTY.displayName"

    /// UserDefaults key for the host-side access policy. Mirrors the
    /// shape used for `nameDefaultsKey`; the sidebar Picker writes this.
    static let accessModeDefaultsKey = "CoTTY.accessMode"

    nonisolated static func savedAccessMode() -> AccessMode {
        let raw = UserDefaults.standard.integer(forKey: accessModeDefaultsKey)
        guard let mode = AccessMode(rawValue: UInt8(clamping: raw)) else {
            return .full
        }
        return mode
    }

    nonisolated static func persistAccessMode(_ mode: AccessMode) {
        UserDefaults.standard.set(Int(mode.rawValue), forKey: accessModeDefaultsKey)
    }

    /// Read the last-error slot populated by the Zig C ABI. Returns nil
    /// if empty.
    nonisolated static func readLastError() -> String? {
        var buf = [UInt8](repeating: 0, count: 512)
        let n = buf.withUnsafeMutableBufferPointer { p -> Int in
            Int(ct_last_error(p.baseAddress, p.count))
        }
        if n == 0 { return nil }
        let len = min(n, buf.count)
        return String(bytes: buf.prefix(len), encoding: .utf8)
    }

    nonisolated static func savedOrDefaultName() -> String {
        if let s = UserDefaults.standard.string(forKey: nameDefaultsKey),
           !s.isEmpty
        {
            return s
        }
        return NSUserName()
    }

    func persistName() {
        UserDefaults.standard.set(localName, forKey: Self.nameDefaultsKey)
    }

    nonisolated static var participantPalette: [UInt32] {
        [
            0xFF3B30, // red
            0xFFD60A, // yellow
            0x32D74B, // green
            0x00C7BE, // teal
            0x64D2FF, // cyan
            0x0A84FF, // blue
            0x5E5CE6, // indigo
            0xBF5AF2, // purple
            0xFF375F, // pink
            0xFF9F0A, // orange
        ]
    }

    nonisolated static func defaultColor(for identity: UserIdentity) -> UInt32 {
        let palette = participantPalette
        return palette[Int(colorHash(for: identity) % UInt32(palette.count))]
    }

    nonisolated static func editorUserID(for identity: UserIdentity) -> UInt32 {
        let hash = colorHash(for: identity)
        // Reserve 0 for deterministic snapshot-loaded CRDT items so anchor
        // ids from initial file contents are replica-stable across peers.
        return hash == 0 ? 1 : hash
    }

    func participant(forEditorUserID editorUserID: UInt32) -> Participant? {
        participants.first { Self.editorUserID(for: $0.identity) == editorUserID }
    }

    func identity(forTransportPeerID peerID: UInt32) -> UserIdentity? {
        if role == .host {
            return transportToIdentity[peerID]
        }
        return nil
    }

    nonisolated static func colorHash(for identity: UserIdentity) -> UInt32 {
        var hash: UInt32 = 2166136261
        for byte in identity.bytes {
            hash ^= UInt32(byte)
            hash &*= 16777619
        }
        return hash
    }
