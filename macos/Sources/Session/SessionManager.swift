import Foundation
import Combine
import CollabTermC

/// Thin Swift wrapper around the C ABI session (`ct_session_*`). Owns the
/// handle, runs a timer-driven poll loop, decodes inbound frames with
/// `FrameCodec`, and exposes role-specific state (`participants`, public URL)
/// for the UI.
///
/// Topology: star. Peers connect to the host; the host is authoritative for
/// the roster and re-broadcasts it whenever someone joins or leaves. Peers
/// read `participants` from the last Roster frame; the host maintains it
/// from Hello frames + lifecycle events.
@MainActor
final class SessionManager: ObservableObject {
    enum Role: Equatable {
        case host
        case peer
    }

    enum State: Equatable {
        case idle
        case starting
        case running
        case reconnecting(attempt: Int)  // peer-only: connection dropped, auto-retrying
        case disconnected  // peer-only: host went away
        case failed(String)
    }

    /// Who's in the session (host + peers), by user identity. Name, color,
    /// and role come from Hello frames. On peers, this list arrives via
    /// Roster broadcasts from the host.
    struct Participant: Identifiable, Equatable {
        var id: UserIdentity { identity }
        var identity: UserIdentity
        var role: SessionRole
        var name: String
        var color: UInt32
    }

    @Published private(set) var role: Role = .host
    @Published private(set) var state: State = .idle
    @Published private(set) var participants: [Participant] = []
    @Published private(set) var localPort: UInt16 = 0
    @Published private(set) var publicURL: String?
    @Published var lastError: String?

    /// Bore relay hostname injected at build time from Secrets.xcconfig.
    static let defaultBoreServer: String = {
        Bundle.main.infoDictionary?["CTBoreServer"] as? String ?? ""
    }()

    /// Bore secret injected at build time from Secrets.xcconfig.
    static let boreSecret: String = {
        Bundle.main.infoDictionary?["CTBoreSecret"] as? String ?? ""
    }()

    /// Bore relay server hostname. Persisted across launches.
    @Published var boreServer: String = {
        UserDefaults.standard.string(forKey: "CoTTY.boreServer") ?? SessionManager.defaultBoreServer
    }() {
        didSet {
            guard boreServer != oldValue else { return }
            UserDefaults.standard.set(boreServer, forKey: "CoTTY.boreServer")
        }
    }

    /// Last mode broadcast by the host. Peers consult this to decide whether
    /// to drop keystrokes and surface a creator-only banner. Defaults to
    /// `.line` so a fresh peer allows input until it hears otherwise.
    @Published private(set) var remoteMode: TermMode = .line

    /// Active access policy.
    /// * Host: source of truth, persisted via UserDefaults
    ///   (`accessModeDefaultsKey`). Toggling it broadcasts an
    ///   `accessMode` frame so peers see the change immediately.
    /// * Peer: shadow copy, updated whenever the host broadcasts
    ///   `accessMode`. Defaults to `.full` so a fresh peer allows
    ///   input until it hears otherwise (matching `remoteMode`).
    @Published private(set) var accessMode: AccessMode = .full

    /// End-to-end encryption key for this session. Generated by the host
    /// and embedded in the share URL; peers set it before calling joinPeer.
    /// Nil means no encryption (no key in URL).
    var sessionKey: SessionKey?

    let localIdentity: UserIdentity
    @Published var localName: String {
        didSet {
            guard oldValue != localName, handle != nil else { return }
            // Local entry mirrors localName; re-announce ourselves.
            updateLocalParticipantField { $0.name = localName }
            sendHello()
            if role == .host { broadcastRoster() }
        }
    }
    var localColor: UInt32

    private var handle: OpaquePointer?
    private var boreHandle: OpaquePointer?
    private var pollTimer: DispatchSourceTimer?
    /// Last interval picked by `schedulePump`. Persists across ticks so the
    /// adaptive backoff can step up/down rather than snapping each cycle.
    private var pollIntervalMs: Int = 16
    private var borePumpTimer: Timer?
    private var keepAliveTimer: Timer?

    /// Host-only: transport peer id → user identity (filled on Hello).
    private var transportToIdentity: [UInt32: UserIdentity] = [:]

    private static let keepAliveInterval: TimeInterval = 15

    /// Peer-only auto-reconnect (#61): the host:port of the last successful
    /// join, kept so a dropped connection can be retried without the user
    /// re-entering the share URL. Cleared by `stop()`.
    private var lastJoinHost: String?
    private var lastJoinPort: UInt16 = 0
    private var reconnectTimer: Timer?
    private var reconnectAttempt = 0
    /// Bumped by `stop()` so an in-flight background connect from a
    /// cancelled reconnect can't resurrect a session the user left.
    private var reconnectGeneration = 0
    static let maxReconnectAttempts = 8

    /// Decoded inbound frame + the transport peer id that sent it.
    var onFrame: ((Frame, UInt32) -> Void)?

    /// Peer-only: fired when the host connection drops and auto-reconnect
    /// starts. UI shows a "reconnecting" notice.
    var onReconnectBegan: (() -> Void)?

    /// Peer-only: fired after the transport is re-established, before Hello
    /// is re-sent. The UI layer must reset join-time state here so the
    /// host's re-join snapshot lands in fresh grids instead of appending to
    /// stale ones.
    var onReconnected: (() -> Void)?

    init(identity: UserIdentity = .random(),
         name: String? = nil,
         color: UInt32? = nil)
    {
        self.localIdentity = identity
        self.localName = name ?? SessionManager.savedOrDefaultName()
        self.localColor = color ?? Self.defaultColor(for: identity)
    }

    deinit {
        pollTimer?.cancel()
        borePumpTimer?.invalidate()
        keepAliveTimer?.invalidate()
        reconnectTimer?.invalidate()
        if let h = handle { ct_session_free(h) }
        if let b = boreHandle { ct_bore_free(b) }
    }

    // MARK: lifecycle

    func startHost(port: UInt16 = 0) {
        guard handle == nil else { return }
        role = .host
        accessMode = Self.savedAccessMode()
        sessionKey = SessionKey()
        state = .starting
        guard let h = ct_session_new_host(port) else {
            state = .failed(Self.readLastError()
                ?? "ct_session_new_host failed")
            return
        }
        handle = h
        localPort = ct_session_port(h)
        participants = [Participant(
            identity: localIdentity, role: .host,
            name: localName, color: localColor)]
        state = .running
        startPolling()
        startKeepAlive()
    }

    /// Connect to `host:port`. `host` can be an IP literal or DNS name
    /// (e.g. "bore.pub"). Blocking; returns once the initial TCP handshake
    /// completes or fails.
    func joinPeer(host: String, port: UInt16) {
        guard handle == nil else { return }
        role = .peer
        accessMode = .full
        state = .starting
        let h = host.withCString { cstr in
            ct_session_new_peer(cstr, port)
        }
        guard let h = h else {
            let detail = Self.readLastError() ?? "unknown error"
            state = .failed("\(detail) — host=\(host) port=\(port)")
            return
        }
        handle = h
        lastJoinHost = host
        lastJoinPort = port
        participants = [Participant(
            identity: localIdentity, role: .peer,
            name: localName, color: localColor)]
        state = .running
        startPolling()
        startKeepAlive()
        sendHello()  // tell the host who we are; host broadcasts Roster back
    }

    func stop() {
        pollTimer?.cancel(); pollTimer = nil
        borePumpTimer?.invalidate(); borePumpTimer = nil
        keepAliveTimer?.invalidate(); keepAliveTimer = nil
        reconnectTimer?.invalidate(); reconnectTimer = nil
        reconnectAttempt = 0
        reconnectGeneration += 1
        lastJoinHost = nil
        lastJoinPort = 0
        if let h = handle {
            ct_session_free(h)
            handle = nil
        }
        if let b = boreHandle {
            ct_bore_free(b)
            boreHandle = nil
        }
        participants.removeAll()
        transportToIdentity.removeAll()
        localPort = 0
        publicURL = nil
        lastError = nil
        sessionKey = nil
        state = .idle
        // Always return to host role so the user can start a new session after
        // leaving a peer session. The role is re-assigned correctly by
        // startHost() / joinPeer() whenever a new session begins.
        role = .host
    }

    // MARK: bore tunnel (host only)

    /// `server`: bore relay hostname (empty = ngrok mode). `secret`: bore --secret value (empty = no auth).
    func startBoreTunnel(borePath: String, server: String = "", secret: String = "") {
        NSLog("[ct] startBoreTunnel role=%@ handle=%@ port=%d path=%@ server=%@",
              role == .host ? "host" : "peer",
              boreHandle == nil ? "nil" : "set",
              Int32(localPort),
              borePath,
              server.isEmpty ? "(ngrok)" : server)
        guard role == .host, boreHandle == nil, localPort != 0 else {
            NSLog("[ct] startBoreTunnel early return")
            return
        }
        publicURL = nil
        lastError = nil
        guard let b = ct_bore_new() else {
            lastError = "ct_bore_new failed"
            NSLog("[ct] ct_bore_new returned nil")
            return
        }
        boreHandle = b
        let rc = borePath.withCString { boreCStr in
            server.withCString { serverCStr in
                secret.withCString { secretCStr in
                    ct_bore_start(b, boreCStr, localPort, serverCStr, secretCStr)
                }
            }
        }
        NSLog("[ct] ct_bore_start rc=%d", rc)
        if rc != 0 {
            lastError = "ct_bore_start failed"
            ct_bore_free(b)
            boreHandle = nil
            return
        }
        startBorePumping()
    }

    // MARK: send helpers

    /// Broadcast to every transport peer (no filtering).
    func broadcast(_ frame: Frame) {
        guard let h = handle else { return }
        guard let data = encryptedWireBytes(FrameCodec.encode(frame)) else { return }
        let rc = data.withUnsafeBytes { raw -> Int32 in
            guard let base = raw.baseAddress else { return -1 }
            return ct_session_broadcast(
                h,
                base.assumingMemoryBound(to: UInt8.self),
                data.count)
        }
        if rc != 0 {
            NSLog("[ct] broadcast failed rc=%d bytes=%d", rc, data.count)
        }
    }

    func send(_ frame: Frame, toTransportPeerID peerID: UInt32) {
        guard let h = handle else { return }
        guard let data = encryptedWireBytes(FrameCodec.encode(frame)) else { return }
        let rc = data.withUnsafeBytes { raw -> Int32 in
            guard let base = raw.baseAddress else { return -1 }
            return ct_session_send_to(
                h,
                peerID,
                base.assumingMemoryBound(to: UInt8.self),
                data.count)
        }
        if rc != 0 {
            NSLog("[ct] send_to failed peer=%u bytes=%d err=%@",
                  peerID, data.count, Self.readLastError() ?? "<unknown>")
        }
    }

    /// Returns nil when encryption fails — the frame must be DROPPED, never
    /// silently downgraded to plaintext on an encrypted session.
    private func encryptedWireBytes(_ plain: Data) -> Data? {
        guard let key = sessionKey else { return plain }
        do {
            return try key.encrypt(plain)
        } catch {
            NSLog("[ct] encrypt failed, frame dropped: %@", "\(error)")
            return nil
        }
    }

    func sendHello() {
        broadcast(.hello(
            localIdentity,
            role: role == .host ? .host : .peer,
            color: localColor,
            name: localName))
    }

    func sendCursor(col: UInt16, row: UInt16) {
        broadcast(.cursorPos(localIdentity, col: col, row: row))
    }

    /// Host only: fan PTY output out to every peer.
    func sendPtyOutput(_ bytes: Data) {
        guard role == .host, state == .running, !bytes.isEmpty else { return }
        broadcast(.ptyOutput(bytes))
    }

    /// Host only: broadcast a mode transition. Idempotent — callers should
    /// gate with their own edge detector.
    func sendMode(_ mode: TermMode) {
        guard role == .host, state == .running else { return }
        remoteMode = mode
        broadcast(.modeChange(mode))
    }

    // MARK: tab send helpers (host only)

    /// Host only: announce a new tab (broadcast or directed).
    func sendTabOpen(tabId: UInt32, title: String,
                     toTransportPeerID peerID: UInt32? = nil)
    {
        guard role == .host, state == .running else { return }
        let frame = Frame.tabOpen(tabId: tabId, title: title)
        if let peerID {
            send(frame, toTransportPeerID: peerID)
        } else {
            broadcast(frame)
        }
    }

    /// Host only: announce a tab teardown.
    func sendTabClose(tabId: UInt32) {
        guard role == .host, state == .running else { return }
        broadcast(.tabClose(tabId: tabId))
    }

    /// Announce which tab the local user is currently focused on. Hosts use
    /// this for initial focus hints; peers use it so the host can keep
    /// per-user tab cursor state separate.
    func sendTabFocus(tabId: UInt32,
                      toTransportPeerID peerID: UInt32? = nil)
    {
        guard state == .running else { return }
        let frame = Frame.tabFocus(tabId: tabId)
        if let peerID {
            send(frame, toTransportPeerID: peerID)
        } else {
            broadcast(frame)
        }
    }

    /// Host only: fan a chunk of PTY output for a specific tab to peers.
    func sendTabPtyOutput(tabId: UInt32, data: Data,
                          toTransportPeerID peerID: UInt32? = nil)
    {
        guard role == .host, state == .running, !data.isEmpty else { return }
        let frame = Frame.tabPtyOutput(tabId: tabId, data: data)
        if let peerID {
            send(frame, toTransportPeerID: peerID)
        } else {
            broadcast(frame)
        }
    }

    /// Peer only: ship keystrokes for one tab to the host. The host writes
    /// them only into the matching PTY, so tabs do not share input state.
    func sendTabInput(tabId: UInt32, data: Data) {
        guard role == .peer, state == .running, !data.isEmpty else { return }
        guard accessMode == .full else { return }
        broadcast(.tabInput(tabId: tabId, data: data))
    }

    // MARK: split-pane send helpers

    /// Host only: announce a new split pane inside a tab.
    func sendPaneOpen(tabId: UInt32, paneId: UInt32, axis: SplitAxis,
                      toTransportPeerID peerID: UInt32? = nil)
    {
        guard role == .host, state == .running else { return }
        let frame = Frame.paneOpen(tabId: tabId, paneId: paneId, axis: axis)
        if let peerID { send(frame, toTransportPeerID: peerID) }
        else { broadcast(frame) }
    }

    /// Host only: announce that a split pane was closed.
    func sendPaneClose(tabId: UInt32, paneId: UInt32) {
        guard role == .host, state == .running else { return }
        broadcast(.paneClose(tabId: tabId, paneId: paneId))
    }

    /// Host only: fan PTY output for a specific split pane to peers.
    func sendPanePtyOutput(paneId: UInt32, data: Data,
                           toTransportPeerID peerID: UInt32? = nil)
    {
        guard role == .host, state == .running, !data.isEmpty else { return }
        let frame = Frame.panePtyOutput(paneId: paneId, data: data)
        if let peerID { send(frame, toTransportPeerID: peerID) }
        else { broadcast(frame) }
    }

    /// Peer only: send keystrokes for a specific split pane to the host.
    func sendPaneInput(paneId: UInt32, data: Data) {
        guard role == .peer, state == .running, !data.isEmpty else { return }
        guard accessMode == .full else { return }
        broadcast(.paneInput(paneId: paneId, data: data))
    }

    /// Broadcast the local user's cursor position within a pane.
    func sendPaneCursor(paneId: UInt32, col: UInt16, row: UInt16) {
        guard state == .running else { return }
        broadcast(.paneCursorPos(localIdentity, paneId: paneId, col: col, row: row))
    }

    /// Host only: relay a peer's pane cursor update to all peers (including
    /// the originator, which will filter its own identity on receipt).
    func relayPaneCursor(from identity: UserIdentity, paneId: UInt32,
                         col: UInt16, row: UInt16)
    {
        guard role == .host, state == .running else { return }
        broadcast(.paneCursorPos(identity, paneId: paneId, col: col, row: row))
    }

    /// Host only: change the access policy and announce it to all peers.
    /// Persisted via `UserDefaults` so subsequent sessions remember the
    /// last preference. Safe to call before any peer has connected — the
    /// stored value is sent automatically when peers say Hello.
    func setAccessMode(_ mode: AccessMode) {
        guard role == .host else { return }
        accessMode = mode
        Self.persistAccessMode(mode)
        if state == .running {
            broadcast(.accessMode(mode))
        }
    }

    /// Host only: announce the current access mode unconditionally. Used
    /// after a peer Hello so a fresh joiner learns the policy without
    /// waiting for the next toggle.
    func broadcastAccessMode() {
        guard role == .host, state == .running else { return }
        broadcast(.accessMode(accessMode))
    }

    /// Peer only: ask the host for full access. Harmless if already full —
    /// the host simply ignores a request when the session isn't view-only.
    func sendControlRequest() {
        guard role == .peer, state == .running else { return }
        broadcast(.requestControl(localIdentity))
    }

    /// Host only: decline a peer's control request so they get explicit
    /// feedback rather than silence. Granting is handled by the existing
    /// `setAccessMode(.full)` path — no separate "granted" frame is needed
    /// because the access-mode broadcast already tells the peer.
    func denyControlRequest(_ identity: UserIdentity) {
        guard role == .host, state == .running else { return }
        guard let peerID = transportToIdentity.first(where: { $0.value == identity })?.key
        else { return }
        send(.controlDenied(identity), toTransportPeerID: peerID)
    }

    /// Host only: remove a participant by identity. Sends a kick frame so the
    /// peer can display a "you were removed" message, then closes their socket.
    func kickPeer(_ identity: UserIdentity) {
        guard role == .host,
              state == .running,
              identity != localIdentity else { return }
        guard let peerID = transportToIdentity.first(where: { $0.value == identity })?.key,
              let h = handle else { return }

        // Notify the peer before the socket drops (TCP ordering guarantees delivery).
        send(.kick(identity), toTransportPeerID: peerID)

        // Close the TCP connection; reader thread fires peer_disconnected async.
        ct_session_drop_peer(h, peerID)

        // Eagerly update local state so the UI is immediately responsive.
        // The async peer_disconnected event will be a no-op (identity already removed).
        transportToIdentity.removeValue(forKey: peerID)
        participants.removeAll { $0.identity == identity }
        broadcastRoster()
    }

    /// Peer only: ship keystroke bytes to the host as an opaque `inputOp`
    /// payload. (Full CRDT merge is a future step; Phase 3 uses this as a
    /// "raw-bytes passthrough" so end-to-end shared typing works.) In
    /// view-only mode this is a no-op so a misbehaving caller can't bypass
    /// the UI gate.
    func sendInputBytes(_ bytes: Data) {
        guard role == .peer, state == .running, !bytes.isEmpty else { return }
        guard accessMode == .full else { return }
        broadcast(.inputOp(bytes))
    }

    func sendEditorOpen(docId: UInt64, path: String, snapshot: Data) {
        guard role == .host, state == .running else { return }
        broadcast(.editorOpen(docId: docId, path: path, snapshot: snapshot))
